// Carousel management
let carouselIndex = 0;
let carouselTouchStart = 0;
let carouselTouchEnd = 0;

function initCarousel() {
    const carousel = document.getElementById("homeCarousel");
    const dotsContainer = document.getElementById("carouselDots");
    
    if (!carousel) return;
    
    const slides = carousel.querySelectorAll(".carousel-slide");
    
    // Create dots
    slides.forEach((_, idx) => {
        const dot = document.createElement("div");
        dot.className = `carousel-dot ${idx === 0 ? 'active' : ''}`;
        dot.onclick = () => goToSlide(idx);
        dotsContainer.appendChild(dot);
    });
    
    // Touch swipe support
    carousel.addEventListener("touchstart", (e) => {
        carouselTouchStart = e.changedTouches[0].screenX;
    }, false);
    
    carousel.addEventListener("touchend", (e) => {
        carouselTouchEnd = e.changedTouches[0].screenX;
        handleSwipe();
    }, false);
    
    updateCarousel();
}

function handleSwipe() {
    if (carouselTouchStart - carouselTouchEnd > 50) {
        carouselNext();
    }
    if (carouselTouchEnd - carouselTouchStart > 50) {
        carouselPrev();
    }
}

function carouselNext() {
    const carousel = document.getElementById("homeCarousel");
    const slides = carousel.querySelectorAll(".carousel-slide");
    carouselIndex = (carouselIndex + 1) % slides.length;
    updateCarousel();
}

function carouselPrev() {
    const carousel = document.getElementById("homeCarousel");
    const slides = carousel.querySelectorAll(".carousel-slide");
    carouselIndex = (carouselIndex - 1 + slides.length) % slides.length;
    updateCarousel();
}

function goToSlide(idx) {
    carouselIndex = idx;
    updateCarousel();
}

function updateCarousel() {
    const carousel = document.getElementById("homeCarousel");
    const dots = document.querySelectorAll(".carousel-dot");
    
    carousel.style.transform = `translateX(-${carouselIndex * 100}%)`;
    
    dots.forEach((dot, idx) => {
        dot.classList.toggle("active", idx === carouselIndex);
    });
}

