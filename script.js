function effectuerConnexion() {
    const email = document.getElementById("loginEmail").value.trim();
    const motDePasse = document.getElementById("loginPassword").value.trim();
    
    if (!email || !motDePasse) {
        showSiteMessage('error', 'Veuillez remplir tous les champs');
        return;
    }
    
    const users = JSON.parse(localStorage.getItem("athenaUsers") || "[]");
    const user = users.find(u => u.email === email && u.password === motDePasse);
    
    if (!user) {
        showSiteMessage('error', 'Email ou mot de passe incorrect');
        return;
    }
    
    currentUser = user;
    localStorage.setItem("athenaUser", JSON.stringify(currentUser));
    afficherMenuUtilisateur();
    fermerModalAuth();
    entrerDansAthena();
}

