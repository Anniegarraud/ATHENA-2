function envoyerCodeReset() {
    const email = document.getElementById('resetEmail').value.trim();
    if (!email) {
        showSiteMessage('error', 'Veuillez saisir votre email');
        return;
    }
    const users = JSON.parse(localStorage.getItem('athenaUsers') || '[]');
    const user = users.find(u => u.email === email);
    if (!user) {
        showSiteMessage('error', 'Aucun compte associé à cet email');
        return;
    }
    // generate 6-digit code
    const code = Math.floor(100000 + Math.random() * 900000).toString();
    const resetStore = JSON.parse(localStorage.getItem('athenaResetCodes') || '{}');
    resetStore[email] = code;
    localStorage.setItem('athenaResetCodes', JSON.stringify(resetStore));
    // simulate sending email
    showSiteMessage('info', 'Un code de réinitialisation a été envoyé à votre email');
    // show code inputs
    document.getElementById('resetCode').style.display = 'block';
    document.getElementById('resetNewPassword').style.display = 'block';
    document.getElementById('resetConfirmBtn').style.display = 'block';
}

function confirmerReset() {
    const email = document.getElementById('resetEmail').value.trim();
    const code = document.getElementById('resetCode').value.trim();
    const newPass = document.getElementById('resetNewPassword').value.trim();
    if (!email || !code || !newPass) {
        showSiteMessage('error', 'Veuillez remplir tous les champs');
        return;
    }
    const resetStore = JSON.parse(localStorage.getItem('athenaResetCodes') || '{}');
    if (!resetStore[email] || resetStore[email] !== code) {
        showSiteMessage('error', 'Code incorrect');
        return;
    }
    const users = JSON.parse(localStorage.getItem('athenaUsers') || '[]');
    const idx = users.findIndex(u => u.email === email);
    if (idx === -1) {
        showSiteMessage('error', 'Compte introuvable');
        return;
    }
    users[idx].password = newPass;
    localStorage.setItem('athenaUsers', JSON.stringify(users));
    // remove code
    delete resetStore[email];
    localStorage.setItem('athenaResetCodes', JSON.stringify(resetStore));
    showSiteMessage('success', 'Mot de passe réinitialisé. Vous pouvez maintenant vous connecter');
    // return to login
    basculerVersConnexion();
}

