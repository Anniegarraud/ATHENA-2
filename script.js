function genererReponse(question) {
    let q = question.toLowerCase();
    if (cours[currentTopic] && cours[currentTopic].lecons) {
        for (let leconKey in cours[currentTopic].lecons) {
            let lecon = cours[currentTopic].lecons[leconKey];
            for (let exemple of lecon.exemples) {
                if (q.includes(exemple.substring(0, 6))) {
                    currentLecon = leconKey;
                    return lecon.titre + "\n" + lecon.contenu;
                }
            }
            if (q.includes(leconKey.split(" ")[0])) {
                return lecon.titre + "\n" + lecon.contenu;
            }
        }
    }
    if (currentTopic && cours[currentTopic] && cours[currentTopic].lecons) {
        return "Je n'ai pas encore de leçon sur ce sujet précis. Pose-moi une autre question ou choisis un des thèmes suivants :\n\n" +
            Object.keys(cours[currentTopic].lecons).map(l => "• " + l).join("\n");
    }
    return "Choisis une matière pour commencer un cours, puis pose ta question !";
}

