function envoyerMessage() {
    let question = document.getElementById("question").value.trim();
    
    // Verifier s'il y a une image
    if (!question && !selectedImage) return;

    // Si aucune matière choisie, démarrer une discussion libre
    if (!currentTopic) {
        document.getElementById("welcomeSection").style.display = "none";
        document.getElementById("topicSection").style.display = "none";
    }

    // Ajouter le message
    if (question) {
        currentChat.push({ role: "user", content: question });
        ajouterMessageUI(question, "user");
    }
    
    // Ajouter l'image si presente
    if (selectedImage) {
        envoyerImageAvecMessage(selectedImage);
        selectedImage = null;
        document.getElementById('imagePreview').style.display = 'none';
        document.getElementById('imageUpload').value = '';
    }
    
    document.getElementById("question").value = "";

    if (question) {
        envoyerViaGroq(question);
    }
}

async function envoyerViaGroq(question) {
    let typingId = afficherTyping();

    try {
        const response = await fetch("/.netlify/functions/athena", {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify({
                model: "llama-3.1-8b-instant",
                messages: [
                    {
                        role: "system",
                        content: getSystemPrompt()
                    },
                    ...aiConversation,
                    {
                        role: "user",
                        content: question
                    }
                ],
                temperature: 0.7,
                max_tokens: 1000
            })
        });

        supprimerTyping(typingId);

        const data = await response.json();

        if (!response.ok) {
            ajouterMessageUI(`Erreur API : ${data.error?.message || "Erreur de proxy Netlify"}`, "athena");
            console.error(data);
            return;
        }

        const reponse = data.choices?.[0]?.message?.content || "Aucune réponse reçue.";

        aiConversation.push({
            role: "user",
            content: question
        });

        aiConversation.push({
            role: "assistant",
            content: reponse
        });

        currentChat.push({ role: "athena", content: reponse });
        ajouterMessageUI(reponse, "athena");

    } catch (error) {
        supprimerTyping(typingId);
        ajouterMessageUI(`Erreur réseau : ${error.message}`, "athena");
        console.error(error);
    }
}

