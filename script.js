// Uniform site message (no random ids)
function showSiteMessage(type, message, timeout = 4500) {
    const el = document.getElementById('siteMessage');
    if (!el) return;
    el.className = 'site-message ' + (type || 'info');
    el.textContent = message;
    el.style.display = 'block';
    // clear any existing timeout
    if (el._hideTimeout) clearTimeout(el._hideTimeout);
    el._hideTimeout = setTimeout(() => {
        el.style.display = 'none';
    }, timeout);
}

