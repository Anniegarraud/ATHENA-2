function demarrerQuiz() {
    const matiere = document.getElementById('quizMatiere').value;
    const niveau = document.getElementById('quizNiveau').value;
    const sujetSpecifique = document.getElementById('quizSujetSpecifique').value.trim();
    const duree = parseInt(document.getElementById('quizDuree').value, 10);
    const nbQuestions = parseInt(document.getElementById('quizNbQuestions').value, 10);
    const points = parseInt(document.getElementById('quizPoints').value, 10);

    if (!matiere) {
        showSiteMessage('error', 'Sélectionne une matière');
        return;
    }
    if (!niveau) {
        showSiteMessage('error', 'Sélectionne un niveau scolaire');
        return;
    }
    if (!sujetSpecifique) {
        showSiteMessage('error', 'Indique un sujet spécifique');
        return;
    }
    if (!duree || duree <= 0) {
        showSiteMessage('error', 'Saisis une durée valide');
        return;
    }

    fermerQuizModal();
    entrerDansAthena();

    quizActive = true;
    quizTimeRemaining = duree * 60;
    afficherQuizTimer();
    demarrerQuizTimer();

    const quizMessage = `Quiz démarré : ${matiere} — ${niveau} — sujet : ${sujetSpecifique} — ${nbQuestions} questions — ${duree} minutes — ${points} points par bonne réponse. \nJe vais te poser des questions sur ${sujetSpecifique}. Réponds dans le champ en bas.`;
    ajouterMessageUI(quizMessage, 'athena');

    const quizPrompt = `Génère un quiz de ${nbQuestions} questions pour un élève du ${niveau}, en ${matiere}, sur le sujet suivant : ${sujetSpecifique}. Donne des questions numérotées et des options de réponse, sans indiquer immédiatement les bonnes réponses.`;
    envoyerViaGroq(quizPrompt);
}

function afficherQuizTimer() {
    const timer = document.getElementById('quizTimer');
    const value = document.getElementById('quizTimerValue');
    if (!timer || !value) return;
    timer.style.display = 'block';
    value.textContent = formatTemps(quizTimeRemaining);
}

function masquerQuizTimer() {
    const timer = document.getElementById('quizTimer');
    if (timer) timer.style.display = 'none';
}

function formatTemps(seconds) {
    const mins = Math.floor(seconds / 60);
    const secs = seconds % 60;
    return `${mins}:${secs < 10 ? '0' : ''}${secs}`;
}

function demarrerQuizTimer() {
    if (quizIntervalId) {
        clearInterval(quizIntervalId);
    }
    quizIntervalId = setInterval(() => {
        if (quizTimeRemaining <= 0) {
            clearInterval(quizIntervalId);
            quizIntervalId = null;
            quizActive = false;
            masquerQuizTimer();
            terminerQuizAutomatic();
            return;
        }
        quizTimeRemaining -= 1;
        const value = document.getElementById('quizTimerValue');
        if (value) {
            value.textContent = formatTemps(quizTimeRemaining);
        }
    }, 1000);
}

function terminerQuizAutomatic() {
    const questionInput = document.getElementById('question');
    const hasText = questionInput && questionInput.value.trim();
    const hasImage = selectedImage !== null;
    if (hasText || hasImage) {
        showSiteMessage('info', 'Temps écoulé — ta réponse a été envoyée automatiquement.');
        envoyerMessage();
        return;
    }
    showSiteMessage('info', 'Temps écoulé !');
}

function stopQuizTimer() {
    if (quizIntervalId) {
        clearInterval(quizIntervalId);
        quizIntervalId = null;
    }
    if (quizTimeoutId) {
        clearTimeout(quizTimeoutId);
        quizTimeoutId = null;
    }
    quizActive = false;
    masquerQuizTimer();
}

