function afficherProfil() {
    // Fill profile form with current user data
    document.getElementById('profileNomInput').value = currentUser.nom || '';
    document.getElementById('profilePrenomInput').value = currentUser.prenom || '';
    document.getElementById('profileEmailInput').value = currentUser.email || '';
    document.getElementById('profilePasswordInput').value = '';
    document.getElementById('profileNiveauInput').value = currentUser.niveauScolaire || '';

    const personaliteSelect = document.getElementById('profilePersonaliteInput');
    personaliteSelect.innerHTML = '';
    PERSONALITES_ATHENA.forEach(p => {
        const option = document.createElement('option');
        option.value = p.id;
        option.textContent = p.nom;
        if (p.id === currentUser.personaliteAthena) option.selected = true;
        personaliteSelect.appendChild(option);
    });

    document.getElementById('profilePage').style.display = 'flex';
    document.getElementById('athenaApp').classList.remove('is-visible');
    document.getElementById('homePage').style.display = 'none';
    toggleUserMenu();
}

function sauvegarderProfil() {
    const nom = document.getElementById('profileNomInput').value.trim();
    const prenom = document.getElementById('profilePrenomInput').value.trim();
    const email = document.getElementById('profileEmailInput').value.trim();
    const password = document.getElementById('profilePasswordInput').value.trim();
    const niveau = document.getElementById('profileNiveauInput').value;
    const personalite = document.getElementById('profilePersonaliteInput').value;

    if (!nom || !prenom || !email || !niveau || !personalite) {
        showSiteMessage('error', 'Merci de remplir tous les champs sauf le mot de passe si vous ne voulez pas le changer.');
        return;
    }

    const users = JSON.parse(localStorage.getItem('athenaUsers') || '[]');
    const idx = users.findIndex(u => u.email === currentUser.email);
    if (idx === -1) {
        showSiteMessage('error', 'Impossible de mettre à jour votre compte.');
        return;
    }

    // Vérifier que le nouvel email n'est pas déjà utilisé par un autre utilisateur
    if (email !== currentUser.email && users.find(u => u.email === email)) {
        showSiteMessage('error', 'Cet email est déjà utilisé par un autre compte.');
        return;
    }

    users[idx].nom = nom;
    users[idx].prenom = prenom;
    users[idx].email = email;
    users[idx].niveauScolaire = niveau;
    users[idx].personaliteAthena = personalite;
    
    // Enregistrer le mot de passe seulement s'il a été modifié
    if (password && password.length > 0) {
        users[idx].password = password;
    }
    
    localStorage.setItem('athenaUsers', JSON.stringify(users));
    currentUser = users[idx];
    localStorage.setItem('athenaUser', JSON.stringify(currentUser));
    afficherMenuUtilisateur();
    showSiteMessage('success', 'Profil enregistré avec succès !');
    
    // Fermer le profil après 1.5 secondes
    setTimeout(() => {
        fermerProfile();
    }, 1500);
}

